"""セルの値のファイル（vormorph cells 形式 v1、TOML）の書き出しと読み込み。

格子ファイル（`meshfile`）のセルと同じ順に、母点の座標と河床高などのセルの値を持つ。Rust 側の
`mesh::cells` が読み、母点の座標で格子と照合する（ADR-0020）。仕様は
`docs/design/mesh-generation.md` の第7章にある。

```toml
format = "vormorph-cells"
version = 1
title = "bend180"        # 格子の名前（格子ファイルの title と同じ）

[meta]                   # 任意の付加情報。読み込み側は解釈しない

[cells]
x = [...]                # 母点の座標 [m]（格子ファイルと同じ値。照合に使う）
y = [...]
zb = [...]               # 河床高 [m]
z_ne = [...]             # 非侵食層の上面の高さ [m]（任意。なければ非侵食層なし）
```
"""

from __future__ import annotations

import tomllib
from pathlib import Path

import numpy as np

from .meshfile import _floats, _string, _value

FORMAT = "vormorph-cells"
VERSION = 1
FIELDS = ("x", "y", "zb", "z_ne")
"""`[cells]` の項目（`z_ne` は任意）。"""


def write(
    path: Path,
    title: str,
    x: np.ndarray,
    y: np.ndarray,
    zb: np.ndarray,
    meta: dict,
    z_ne: np.ndarray | None = None,
) -> None:
    """セルの値を TOML で書き出す。浮動小数点数は往復で値が変わらない最短の表記にする。"""
    n = len(x)
    if any(len(v) != n for v in (y, zb) + ((z_ne,) if z_ne is not None else ())):
        raise ValueError("x, y, zb (and z_ne) must have the same length")
    lines = [
        "# vormorph cell values (generated by tools/make_bed.py; see docs/design/mesh-generation.md)",
        f'format = "{FORMAT}"',
        f"version = {VERSION}",
        f"title = {_string(title)}",
        "",
        "[meta]",
        *(f"{key} = {_value(value)}" for key, value in meta.items()),
        "",
        "[cells]",
        f"x = {_floats(np.asarray(x, dtype=float))}",
        f"y = {_floats(np.asarray(y, dtype=float))}",
        f"zb = {_floats(np.asarray(zb, dtype=float))}",
    ]
    if z_ne is not None:
        lines.append(f"z_ne = {_floats(np.asarray(z_ne, dtype=float))}")
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def read(path: Path) -> tuple[dict[str, np.ndarray], dict]:
    """セルの値のファイルを読み、項目ごとの配列と、ファイルの先頭の項目（title, meta）を返す。"""
    with open(path, "rb") as f:
        data = tomllib.load(f)
    if data.get("format") != FORMAT or data.get("version") != VERSION:
        raise ValueError(f"{path}: not a {FORMAT} v{VERSION} file")
    cells = data["cells"]
    unknown = sorted(set(cells) - set(FIELDS))
    if unknown:
        raise ValueError(f"{path}: unknown keys in [cells]: {', '.join(unknown)}")
    values = {key: np.asarray(cells[key], dtype=float) for key in FIELDS if key in cells}
    header = {k: data[k] for k in ("title", "meta") if k in data}
    return values, header
