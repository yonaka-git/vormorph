"""格子ファイル（vormorph mesh 形式 v1、TOML）の書き出しと読み込み。

Rust 側の `mesh::file` が読む形式。仕様は `docs/design/mesh-generation.md` にある。

```toml
format = "vormorph-mesh"
version = 1
title = "bend180"
cell_order = "hilbert"

[meta]                 # 任意の付加情報（生成条件など）。読み込み側は解釈しない
cell_size = 1.0

[cells]
x = [...]              # 母点の座標 [m]
y = [...]
vertices = [[...], ...]  # セルの頂点番号（反時計回り）

[vertices]
x = [...]              # ボロノイ頂点の座標 [m]
y = [...]

[boundary]             # 境界辺の両端の頂点番号（セルから見て反時計回りの向き）
wall = [[a, b], ...]
upstream = [[a, b], ...]
downstream = [[a, b], ...]
```
"""

from __future__ import annotations

import math
import tomllib
from collections.abc import Iterable
from pathlib import Path

import numpy as np

from .domain import KINDS
from .voronoi import PolygonMesh

FORMAT = "vormorph-mesh"
VERSION = 1


def write(path: Path, mesh: PolygonMesh, title: str, cell_order: str, meta: dict) -> None:
    """格子を TOML で書き出す。浮動小数点数は往復で値が変わらない最短の表記にする。"""
    lines = [
        "# vormorph mesh (generated by tools/make_mesh.py; see docs/design/mesh-generation.md)",
        f'format = "{FORMAT}"',
        f"version = {VERSION}",
        f"title = {_string(title)}",
        f'cell_order = "{cell_order}"',
        "",
        "[meta]",
        *(f"{key} = {_value(value)}" for key, value in meta.items()),
        "",
        "[cells]",
        f"x = {_floats(mesh.x_cell)}",
        f"y = {_floats(mesh.y_cell)}",
        "vertices = [",
        *(f"  [{', '.join(map(str, cell))}]," for cell in mesh.cells),
        "]",
        "",
        "[vertices]",
        f"x = {_floats(mesh.x_vertex)}",
        f"y = {_floats(mesh.y_vertex)}",
        "",
        "[boundary]",
        *(f"{kind} = {_pairs(mesh.boundary.get(kind, []))}" for kind in KINDS),
    ]
    Path(path).write_text("\n".join(lines) + "\n", encoding="utf-8")


def read(path: Path) -> tuple[PolygonMesh, dict]:
    """格子ファイルを読み、多角形格子と、ファイルの先頭の項目（title, cell_order, meta）を返す。"""
    with open(path, "rb") as f:
        data = tomllib.load(f)
    if data.get("format") != FORMAT or data.get("version") != VERSION:
        raise ValueError(f"{path}: not a {FORMAT} v{VERSION} file")
    cells, verts, boundary = data["cells"], data["vertices"], data.get("boundary", {})
    mesh = PolygonMesh(
        x_cell=np.asarray(cells["x"], dtype=float),
        y_cell=np.asarray(cells["y"], dtype=float),
        x_vertex=np.asarray(verts["x"], dtype=float),
        y_vertex=np.asarray(verts["y"], dtype=float),
        cells=[list(c) for c in cells["vertices"]],
        boundary={k: [tuple(p) for p in boundary.get(k, [])] for k in KINDS},
    )
    header = {k: data[k] for k in ("title", "cell_order", "meta") if k in data}
    return mesh, header


def _float(v: float) -> str:
    v = float(v)
    if not math.isfinite(v):
        raise ValueError(f"non-finite value {v} cannot be written")
    return repr(v)


def _wrap(items: Iterable[str], per_line: int) -> str:
    items = list(items)
    if not items:
        return "[]"
    rows = [", ".join(items[k : k + per_line]) for k in range(0, len(items), per_line)]
    return "[\n" + "".join(f"  {row},\n" for row in rows) + "]"


def _floats(values: np.ndarray) -> str:
    return _wrap((_float(v) for v in values), 6)


def _pairs(pairs: list[tuple[int, int]]) -> str:
    return _wrap((f"[{a}, {b}]" for a, b in pairs), 8)


def _string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int | np.integer):
        return str(int(v))
    if isinstance(v, float | np.floating):
        return _float(v)
    if isinstance(v, str):
        return _string(v)
    raise TypeError(f"unsupported meta value {v!r}")
